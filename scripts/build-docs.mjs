function renderApiOperation(operation) {
  const requestExample = operation.requestBody?.example;
  const response = operation.responses.find((item) => /^2/.test(item.status)) || operation.responses[0];
  const responseExample = response?.example;
  const schemas = [
    operation.requestBody?.schema ? { label: "Request schema", schema: operation.requestBody.schema } : null,
    response?.schema ? { label: `Response schema · ${response.status}`, schema: response.schema } : null
  ].filter(Boolean);
  const authLabel = operation.security?.length ? "Authentication required" : "Public operation";
  const tags = operation.tags.length ? operation.tags.join(" · ") : "Untagged";
  const responseList = operation.responses.length
    ? `<section><h2>Responses</h2><div class="api-response-list">${operation.responses.map((item) => `<div class="api-response"><code class="api-response__status api-response__status--${item.status.startsWith("2") ? "success" : "error"}">${escapeHtml(item.status)}</code><span>${escapeHtml(item.description || "No description provided.")}</span><small>${escapeHtml(item.contentType || "No response body")}</small></div>`).join("")}</div></section>`
    : "";
  const parameters = operation.parameters.length
    ? `<section><h2>Parameters</h2><div class="api-parameter-list">${operation.parameters.map((parameter) => `<div class="api-parameter"><code>${escapeHtml(parameter.name)}</code><span>${escapeHtml(parameter.in)}${parameter.required ? " · required" : ""}</span><p>${escapeHtml(parameter.description || "No description provided.")}</p></div>`).join("")}</div></section>`
    : "";
  const sections = [
    parameters,
    requestExample !== undefined ? `<section><h2>Request example</h2><pre><code>${escapeHtml(JSON.stringify(requestExample, null, 2))}</code></pre></section>` : "",
    responseExample !== undefined ? `<section><h2>Success response · ${escapeHtml(response.status)}</h2><pre><code>${escapeHtml(JSON.stringify(responseExample, null, 2))}</code></pre></section>` : "",
    schemas.length ? `<section><h2>Schemas</h2><div class="api-schema-grid">${schemas.map((item) => `<div class="api-schema"><span>${escapeHtml(item.label)}</span><pre><code>${escapeHtml(JSON.stringify(item.schema, null, 2))}</code></pre></div>`).join("")}</div></section>` : "",
    responseList
  ].filter(Boolean).join("\n");
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(operation.summary)} · API reference</title>
    <meta name="description" content="${escapeHtml(operation.description || operation.summary)}" />
    <link rel="stylesheet" href="/docs/docs.css" />
    <link rel="stylesheet" href="/api/api.css" />
  </head>
  <body>
    <main class="docs-shell api-shell">
      <header class="docs-header"><a class="docs-brand" href="/"><span>V</span> ${escapeHtml(config.site.name)}</a><a class="docs-source" href="/api/">API reference ↗</a></header>
      <article class="api-operation-page">
        <div class="api-operation-heading"><span class="api-operation-card__method api-method--${operation.method.toLowerCase()}">${escapeHtml(operation.method)}</span><code>${escapeHtml(operation.path)}</code></div>
        <h1>${escapeHtml(operation.summary)}</h1>
        <p class="api-operation-lede">${escapeHtml(operation.description || "Generated from the OpenAPI contract.")}</p>
        <div class="api-operation-meta"><span>${escapeHtml(authLabel)}</span><span>${escapeHtml(tags)}</span><span>${escapeHtml(operation.source)}</span></div>
        <div class="docs-index-actions"><a href="/api/#${encodeURIComponent(operation.id)}">Open request preview ↗</a><a href="/api/openapi/operation?id=${encodeURIComponent(operation.id)}">JSON operation ↗</a></div>${sections ? `\n        ${sections}` : ""}
      </article>
    </main>
  </body>
</html>
`;
}

await writeFile(join(publicDirectory, "index.html"), renderIndex());
await writeFile(join(apiPublicDirectory, "index.json"), `${JSON.stringify(apiIndex, null, 2)}\n`);
