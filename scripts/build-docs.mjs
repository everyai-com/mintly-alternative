for (const operation of apiIndex.operations) {
  const operationDirectory = join(apiPublicDirectory, operation.id);
  await mkdir(operationDirectory, { recursive: true });
  await writeFile(join(operationDirectory, "index.json"), `${JSON.stringify(operation, null, 2)}\n`);
  await writeFile(join(operationDirectory, "index.html"), renderApiOperation(operation));
}

